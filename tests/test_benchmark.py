import json
import io
import tempfile
import unittest
from contextlib import redirect_stdout
from pathlib import Path
from unittest.mock import patch

from medorchestrate.app import app
from medorchestrate.benchmark import (
    BEIR_NFCORPUS_ARCHIVE_MD5, BM25Index, benchmark_status, digest, evaluate_benchmark,
    freeze_manifest, load_benchmark, main,
)


class BenchmarkTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(dir=Path(__file__).resolve().parent)
        self.addCleanup(self.temp.cleanup)
        self.folder = Path(self.temp.name)
        (self.folder / 'qrels').mkdir()
        documents = [
            {'_id': 'd1', 'title': 'Kidney disease treatment', 'text': 'Treatment for kidney disease'},
            {'_id': 'd2', 'title': 'Asthma treatment', 'text': 'Inhaled treatment for asthma'},
            {'_id': 'd3', 'title': 'Kidney function', 'text': 'Monitoring kidney function'},
        ]
        queries = [{'_id': 'q1', 'text': 'kidney treatment'}, {'_id': 'q2', 'text': 'asthma treatment'}]
        (self.folder / 'corpus.jsonl').write_text('\n'.join(map(json.dumps, documents)) + '\n', encoding='utf-8')
        (self.folder / 'queries.jsonl').write_text('\n'.join(map(json.dumps, queries)) + '\n', encoding='utf-8')
        (self.folder / 'qrels' / 'test.tsv').write_text(
            'query-id\tcorpus-id\tscore\nq1\td1\t2\nq1\td3\t1\nq2\td2\t2\n', encoding='utf-8'
        )

    def freeze(self, dataset_id='toy'):
        return freeze_manifest(
            self.folder, dataset_id=dataset_id, edition='tiny test sample',
            source_url='https://example.org/source', license_statement='Generated by the unit test',
            rights_source_url='https://example.org/rights', citation='Unit test fixture', rights_reviewed=True,
        )

    def test_freeze_load_evaluate_and_api(self):
        manifest = self.freeze()
        self.assertEqual(set(manifest['file_sha256']), {'corpus.jsonl', 'queries.jsonl', 'qrels/test.tsv'})
        loaded, documents, queries, qrels = load_benchmark(self.folder)
        self.assertEqual(loaded['kind'], 'real_benchmark')
        self.assertEqual(loaded['rights_review'], 'source_reviewed_academic_local_use')
        self.assertEqual((len(documents), len(queries), len(qrels)), (3, 2, 2))
        self.assertEqual(BM25Index(documents).rank('asthma treatment', 2)[0], 'd2')
        report = evaluate_benchmark(self.folder, k=2)
        self.assertEqual(report['route'], 'direct_bm25')
        self.assertEqual(report['judged_query_count'], 2)
        self.assertTrue(all(0 <= value <= 1 for value in report['metrics'].values()))
        with patch('medorchestrate.benchmark.benchmark_dir', return_value=self.folder):
            client = app.test_client()
            status = client.get('/api/benchmark/status')
            self.assertTrue(status.get_json()['available'])
            result = client.get('/api/benchmark/evaluation?k=2')
            self.assertEqual(result.status_code, 200)
            self.assertEqual(result.get_json()['dataset'], 'toy')

    def test_cli_writes_deterministic_trec_run_and_report_hash(self):
        self.freeze()
        run_path = self.folder / 'baseline.run'
        report_path = self.folder / 'report.json'
        args = ['benchmark', 'evaluate', '--data-dir', str(self.folder), '--k', '2',
                '--run-output', str(run_path), '--output', str(report_path)]
        with patch('sys.argv', args), redirect_stdout(io.StringIO()):
            main()
        first = run_path.read_bytes()
        report = json.loads(report_path.read_text(encoding='utf-8'))
        self.assertEqual(report['run_manifest']['run_sha256'], digest(run_path))
        self.assertIn(b'\tQ0\t', first)
        with patch('sys.argv', args), redirect_stdout(io.StringIO()):
            main()
        self.assertEqual(run_path.read_bytes(), first)

    def test_sha256_tampering_rejected(self):
        self.freeze()
        with (self.folder / 'corpus.jsonl').open('a', encoding='utf-8') as stream:
            stream.write(json.dumps({'_id': 'd4', 'title': 'New', 'text': 'Changed after freeze'}) + '\n')
        with self.assertRaisesRegex(ValueError, 'SHA-256 mismatch'):
            load_benchmark(self.folder)
        self.assertFalse(benchmark_status(self.folder)['available'])

    def test_optional_train_dev_are_hashed_and_disjoint(self):
        query_path = self.folder / 'queries.jsonl'
        with query_path.open('a', encoding='utf-8') as stream:
            stream.write(json.dumps({'_id': 'q3', 'text': 'kidney function'}) + '\n')
            stream.write(json.dumps({'_id': 'q4', 'text': 'asthma'}) + '\n')
        train = self.folder / 'qrels' / 'train.tsv'
        dev = self.folder / 'qrels' / 'dev.tsv'
        train.write_text('query-id\tcorpus-id\tscore\nq3\td3\t1\n', encoding='utf-8')
        dev.write_text('query-id\tcorpus-id\tscore\nq4\td2\t1\n', encoding='utf-8')
        manifest = self.freeze()
        self.assertEqual(manifest['split_query_counts'], {'test': 2, 'train': 1, 'dev': 1})
        self.assertIn('qrels/train.tsv', manifest['file_sha256'])
        self.assertIn('qrels/dev.tsv', manifest['file_sha256'])
        train.write_text('query-id\tcorpus-id\tscore\nq1\td1\t1\n', encoding='utf-8')
        with self.assertRaisesRegex(ValueError, 'SHA-256 mismatch'):
            load_benchmark(self.folder)
        with self.assertRaisesRegex(ValueError, 'overlap'):
            self.freeze()

    def test_incompatible_qrels_rejected_before_freeze(self):
        (self.folder / 'qrels' / 'test.tsv').write_text(
            'query-id\tcorpus-id\tscore\nq1\tmissing\t1\n', encoding='utf-8'
        )
        with self.assertRaisesRegex(ValueError, 'Unknown query/document'):
            self.freeze()

    def test_demo_identity_and_unverified_nfcorpus_archive_rejected(self):
        with self.assertRaisesRegex(ValueError, 'Invalid real benchmark'):
            self.freeze('fictional-demo-v1')
        with self.assertRaisesRegex(ValueError, 'requires qrels/train.tsv'):
            self.freeze('nfcorpus')
        with (self.folder / 'queries.jsonl').open('a', encoding='utf-8') as stream:
            stream.write(json.dumps({'_id': 'q3', 'text': 'kidney function'}) + '\n')
            stream.write(json.dumps({'_id': 'q4', 'text': 'asthma'}) + '\n')
        (self.folder / 'qrels' / 'train.tsv').write_text('query-id\tcorpus-id\tscore\nq3\td3\t1\n', encoding='utf-8')
        (self.folder / 'qrels' / 'dev.tsv').write_text('query-id\tcorpus-id\tscore\nq4\td2\t1\n', encoding='utf-8')
        with self.assertRaisesRegex(ValueError, 'original archive'):
            self.freeze('nfcorpus')

    def test_nfcorpus_identity_requires_pinned_extracted_hashes(self):
        with (self.folder / 'queries.jsonl').open('a', encoding='utf-8') as stream:
            stream.write(json.dumps({'_id': 'q3', 'text': 'kidney function'}) + '\n')
            stream.write(json.dumps({'_id': 'q4', 'text': 'asthma'}) + '\n')
        (self.folder / 'qrels' / 'train.tsv').write_text('query-id\tcorpus-id\tscore\nq3\td3\t1\n', encoding='utf-8')
        (self.folder / 'qrels' / 'dev.tsv').write_text('query-id\tcorpus-id\tscore\nq4\td2\t1\n', encoding='utf-8')
        manifest = self.freeze()
        manifest['dataset_id'] = 'nfcorpus'
        manifest['archive_md5'] = BEIR_NFCORPUS_ARCHIVE_MD5
        (self.folder / 'benchmark_manifest.json').write_text(json.dumps(manifest), encoding='utf-8')
        with self.assertRaisesRegex(ValueError, 'pinned BEIR edition'):
            load_benchmark(self.folder)

    def test_missing_benchmark_explained_and_api_blocks_evaluation(self):
        missing = self.folder / 'missing'
        self.assertIn('manifest missing', benchmark_status(missing)['reason'])
        with patch('medorchestrate.benchmark.benchmark_dir', return_value=missing):
            client = app.test_client()
            self.assertFalse(client.get('/api/benchmark/status').get_json()['available'])
            self.assertEqual(client.get('/api/benchmark/evaluation').status_code, 409)


if __name__ == '__main__':
    unittest.main()
